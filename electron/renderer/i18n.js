  const ALIAS = { zh:'cn', ar:'arab', fa:'farsi', yue:'hk', kat:'ka', kaz:'kk', nld:'nl', ell:'el', uzb:'uz', hye:'hy', srp:'sr', ukr:'uk' };
  let _saved = localStorage.getItem('dai-miner-lang') || 'en';
  let _lang = ALIAS[_saved] || _saved;
  if (!T[_lang]) _lang = 'en';

  function t(key) {
    return (T[_lang] && T[_lang][key]) || (T.en && T.en[key]) || key;
  }

  function applyTranslations() {
    document.querySelectorAll('[data-i18n]').forEach(function (el) {
      el.textContent = t(el.getAttribute('data-i18n'));
    });
    document.querySelectorAll('[data-i18n-placeholder]').forEach(function (el) {
      el.placeholder = t(el.getAttribute('data-i18n-placeholder'));
    });
  }

  function setLanguage(lang) {
    if (!T[lang]) return;
    _lang = lang;
    localStorage.setItem('dai-miner-lang', lang);
    document.documentElement.lang = ({cn:'zh-CN',hk:'zh-HK',arab:'ar',farsi:'fa',sg:'en-SG'}[lang] || lang);
    document.documentElement.dir = (lang === 'arab' || lang === 'farsi' || lang === 'ur') ? 'rtl' : 'ltr';
    applyTranslations();
    var sel = document.getElementById('settings-language');
    if (sel) sel.value = lang;
  }

  function buildLangSelector(selectEl) {
    if (!selectEl) return;
    selectEl.innerHTML = '';
    Object.keys(T).forEach(function (code) {
      var opt = document.createElement('option');
      opt.value = code;
      opt.textContent = LANG_NAMES[code] || code;
      if (code === _lang) opt.selected = true;
      selectEl.appendChild(opt);
    });
    selectEl.addEventListener('change', function () { setLanguage(this.value); });
  }

  window.t = t;
  window.setLanguage = setLanguage;
  window.applyTranslations = applyTranslations;
  window.buildLangSelector = buildLangSelector;
  window.LANG_NAMES = LANG_NAMES;

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', applyTranslations);
  } else {
    applyTranslations();
  }
